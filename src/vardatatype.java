public class vardatatype {
    public static void main(String[] args) {
        // var data type
        var  x = 100 ;
        System.out.println(x);
        var  y = "heng";
        System.out.println(y);
        var z = 1.22 ;
        System.out.println(z);
        var l = 1.45f  ;
        System.out.println(l);
        var x2 = 10 ;
        x2 = 22 ;
        // why output is 100
        System.out.println(x);
    }
}
